/** Troca `{nivel}` e afins pelo valor. */
export function textoDaFicha(modelo: string, valores: Record<string, string | number> = {}): string {
  return modelo.replace(/\{(\w+)\}/g, (_, k: string) => String(valores[k] ?? ''));
}
